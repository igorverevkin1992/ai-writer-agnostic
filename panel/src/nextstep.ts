export type Tab = "чтение" | "правки" | "приёмка" | "ручной" | "история";
export const TABS: readonly Tab[] = ["чтение", "правки", "приёмка", "ручной", "история"];
export const TAB_LABEL: Record<Tab, string> = {
  чтение: "Чтение с флагами", правки: "Правки", приёмка: "Приёмка", ручной: "Окно / ручной режим", история: "История",
};

export interface NextStep {
  /** подсказка автору: что нажать или заполнить */
  label: string;
  /** вкладка, которую стоит подсветить и открыть (если шаг делается во вкладке) */
  tab?: Tab;
}

export interface NextStepContext {
  unresolved: number;
  diffClean: boolean | null;
  hasEdits: boolean;
  hasBatch: boolean;
}

export function nextStep(state: string, ctx: NextStepContext): NextStep {
  switch (state) {
    case "не-начато":
      return { label: "Нажмите «Собрать окно» (или «Продолжить такт ▶» — машинные шаги до паузы автора)." };
    case "собрано":
      return { label: "Нажмите «Написать главу». Без ключа API — вкладка «Окно / ручной режим»." };
    case "сгенерировано":
      return { label: "Нажмите «Проверить Э1» (формальные проверки по нормам канона)." };
    case "верифицировано-1":
      return { label: "Нажмите «Проверить Э2». Без ключа API — вкладка «Окно / ручной режим»." };
    case "верифицировано-2":
      return { label: "Нажмите «Пакет приёмки» — появятся правки.md и решения по самоволкам." };
    case "на-приёмке": {
      const parts: string[] = [];
      if (ctx.unresolved > 0) parts.push(`решите самоволки (${ctx.unresolved}) во вкладке «Чтение с флагами»`);
      parts.push(ctx.hasEdits ? "проверьте правки во вкладке «Правки»" : "заполните правки во вкладке «Правки» (или «Заменить на…» в чтении)");
      return {
        label: `${parts.join(", ")}; затем «Внести правки Писателем».`.replace(/^./, (c) => c.toUpperCase()),
        tab: ctx.unresolved > 0 ? "чтение" : "правки",
      };
    }
    case "правки":
      return { label: "Нажмите «Дифф-контроль» — проверка, что внесено ровно то, что просили." };
    case "дифф-контроль":
      if (ctx.diffClean === false) {
        return {
          label: "Дифф-контроль не чист: см. вкладку «Приёмка» — «Повторить правки» или «Дифф-контроль как авторская правка».",
          tab: "приёмка",
        };
      }
      if (ctx.unresolved > 0) {
        return { label: `Решите самоволки (${ctx.unresolved}) во вкладке «Чтение с флагами», затем «Принять главу».`, tab: "чтение" };
      }
      return { label: "Нажмите «Принять главу» (явное подтверждение, FR-E4).", tab: "приёмка" };
    case "принято":
      return ctx.hasBatch
        ? { label: "Проверьте пакет во вкладке «Приёмка», уберите лишнее, затем «Применить пакет + коммит».", tab: "приёмка" }
        : { label: "Нажмите «Пакет в канон» — Канонист соберёт пакет записей, вы его проверите во вкладке «Приёмка»." };
    case "зафиксировано":
      return { label: "Такт завершён — глава в каноне ✓" };
    case "повреждено":
      return { label: "Файлы главы повреждены — см. состояние.yaml в папке главы." };
    default:
      return { label: "" };
  }
}

