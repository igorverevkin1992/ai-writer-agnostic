# следствия внедрённого противоречия в смежных реестрах (перекрёстные ссылки) — не шум
CONSEQUENCES = {"ХРОН-2": {"КАНОН-1"}, "ЗАКЛ-1": {"ЗАКЛ-2"}, "ФОКАЛ-1": {"МАТР-2"}}


def test_на_каждый_код_линтера_есть_случай():
    """Новый код без внедрённого противоречия в CASES — красный тест (приёмка 7.11)."""
    impl = {c for codes, _ in lint.CHECKS for c in codes}
    covered = {case[1] for case in CASES.values()}
    assert impl == covered, (impl - covered, covered - impl)


@pytest.mark.parametrize("case", list(CASES))
def test_линтер_каждый_класс_ловится(ws, library, case):
    edits, code, *rest = CASES[case]
    volume = rest[0] if rest else 1
    exporter.run_export(library, ws.exports, ws.logs, volume)
    baseline = _codes(lint.run_lint(library, ws.exports, ws.logs, volume=volume, use_cache=False))
    for file, old, new in edits:
        path = library / file
        if old is None:
            path.write_text(new, encoding="utf-8")
        else:
            _edit(path, old, new)
        if file.startswith("21_") and old is None:
            man = manifest_mod.load(ws.root)
            man.библиотека.append(manifest_mod.LibraryEntry(файл=file, тип="каркасы", том=volume))
            manifest_mod.save(ws.root, man)
    report = lint.run_lint(library, ws.exports, ws.logs, volume=volume, use_cache=False)
    codes = _codes(report)
    assert code in codes, [f.message for f in report.findings]
    extra = codes - baseline - {code} - CONSEQUENCES.get(code, set())
    assert not extra, f"лишние находки: {[f.message for f in report.findings if f.code in extra]}"
    for f in report.findings:
        if f.code == code:
            assert f.file and "Что сделать" in f.message  # файл и подсказка (FR-LT-1, FR-LT-6)


